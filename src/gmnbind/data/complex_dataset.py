"""Dataset of processed complexes: (protein graph, ligand graph) pairs loaded from .pt files."""
import os
import torch
from torch.utils.data import Dataset
from torch_geometric.data import Batch


class ComplexDataset(Dataset):
    """
    Loads (protein_{code}.pt, ligand_{code}.pt) pairs generated by PDBbindDataset.
    Each item is a tuple (protein_data, ligand_data) with the same pdb_code and pAffinity (y).
    """

    def __init__(self, processed_dir, pdb_codes):
        self.processed_dir = processed_dir
        self.pdb_codes = list(pdb_codes)

    def __len__(self):
        return len(self.pdb_codes)

    def __getitem__(self, idx):
        code = self.pdb_codes[idx]
        protein = torch.load(
            os.path.join(self.processed_dir, f'protein_{code}.pt'), weights_only=False
        )
        ligand = torch.load(
            os.path.join(self.processed_dir, f'ligand_{code}.pt'), weights_only=False
        )
        return protein, ligand


def complex_collate_fn(batch):
    """DataLoader collate: split the (protein, ligand) tuples and build two PyG Batch objects."""
    proteins, ligands = zip(*batch)  # unzip into two separate lists
    return Batch.from_data_list(list(proteins)), Batch.from_data_list(list(ligands))
